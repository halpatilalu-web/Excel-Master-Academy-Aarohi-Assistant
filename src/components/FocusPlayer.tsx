const STORAGE_KEY = "excel-academy:focus";

interface SavedFocus {
  track: string;
  volume: number;
  loop: boolean;
  open: boolean;
}

function readSaved(): SavedFocus {
  const fallback: SavedFocus = { track: FOCUS_TRACKS[0].id, volume: 0.55, loop: true, open: false };
  if (typeof window === "undefined") return fallback;
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY);
    if (!raw) return fallback;
    const parsed = JSON.parse(raw) as Partial<SavedFocus>;
    return {
      track: FOCUS_TRACKS.some((t) => t.id === parsed.track) ? (parsed.track as string) : fallback.track,
      volume: typeof parsed.volume === "number" ? Math.min(1, Math.max(0, parsed.volume)) : fallback.volume,
      loop: typeof parsed.loop === "boolean" ? parsed.loop : fallback.loop,
      open: typeof parsed.open === "boolean" ? parsed.open : fallback.open,
    };
  } catch {
    return fallback;
  }
}

export function FocusPlayer() {
  const saved = useMemo(readSaved, []);
  const [trackId, setTrackId] = useState(saved.track);
  /** Master switch + volume + loop live in the shared settings store, so the
   *  Settings app and this panel are always the same switch. */
  const [musicOn, setMusicOn] = useSetting("music");
  const [volume, setVolume] = useSetting("musicVolume");
  const [loop, setLoop] = useSetting("musicLoop");
  const [lyricsOn, setLyricsOn] = useSetting("lyrics");
  const [muted, setMuted] = useState(false);
  const [open, setOpen] = useState(saved.open);
  const [playing, setPlaying] = useState(false);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  /** Seconds into the current bed — the lyric line is picked from this. */
  const [position, setPosition] = useState(0);
  const audioRef = useRef<HTMLAudioElement | null>(null);

  const track = FOCUS_TRACKS.find((entry) => entry.id === trackId) ?? FOCUS_TRACKS[0];
  const index = FOCUS_TRACKS.findIndex((entry) => entry.id === track.id);

  /** Create the element only when it is first needed — never on page load. */
  const ensureAudio = useCallback(() => {
    if (audioRef.current) return audioRef.current;
    const audio = new Audio();
    audio.preload = "auto";
    audio.loop = true;
    audio.addEventListener("loadstart", () => setLoading(true));
    audio.addEventListener("canplay", () => setLoading(false));
    audio.addEventListener("waiting", () => setLoading(true));
    audio.addEventListener("playing", () => {
      setLoading(false);
      setPlaying(true);
    });
    audio.addEventListener("pause", () => setPlaying(false));
    // 4× a second is enough for a lyric line and cheap on a phone.
    audio.addEventListener("timeupdate", () => setPosition(audio.currentTime));
    audio.addEventListener("error", () => {
      setLoading(false);
      setPlaying(false);
      setError("Track load nahi hua — internet ya file path check karo.");
    });
    audioRef.current = audio;
    return audio;
  }, []);

  // Keep the element in step with the controls (but never start playback here).
  useEffect(() => {
    const audio = audioRef.current;
    if (!audio) return;
    audio.volume = muted ? 0 : volume;
    audio.loop = loop;
  }, [volume, muted, loop]);

  /**
   * The master switch. Turning music *off* must actually stop the sound — the
   * old player had no off at all: once it was playing, only a page reload or
   * the pause button ended it.
   */
  useEffect(() => {
    if (musicOn) return;
    const audio = audioRef.current;
    if (audio) {
      audio.pause();
      audio.removeAttribute("src");
      audio.load();
    }
    setPlaying(false);
    setLoading(false);
    setPosition(0);
  }, [musicOn]);

  // Free the element and stop the sound when the player unmounts.
  useEffect(
    () => () => {
      const audio = audioRef.current;
      if (audio) {
        audio.pause();
        audio.src = "";
      }
    },
    [],
  );

  useEffect(() => {
    try {
      window.localStorage.setItem(STORAGE_KEY, JSON.stringify({ track: trackId, volume, loop, open }));
    } catch {
      /* private mode: music still works, only the memory of it does not */
    }
  }, [trackId, volume, loop, open]);

  const start = useCallback(
    (src: string) => {
      const audio = ensureAudio();
      setError(null);
      setLoading(true);
      audio.src = src;
      audio.volume = muted ? 0 : volume;
      audio.loop = loop;
      // play() returns a promise; a rejection means the browser refused (or the
      // file is missing) — surface it instead of pretending the music started.
      void audio
        .play()
        .then(() => setPlaying(true))
        .catch(() => {
          setPlaying(false);
          setLoading(false);
          setError("Browser ne play block kiya — dobara dabao.");
        });
    },
    [ensureAudio, loop, muted, volume],
  );

  const toggle = useCallback(() => {
    const audio = audioRef.current;
    if (audio && playing && !audio.paused) {
      audio.pause();
      setPlaying(false);
      return;
    }
    start(track.src);
  }, [playing, start, track.src]);

  /**
   * Next / previous song. Keeps playing when it already was, so a student can
   * skip through the playlist without pressing play again.
   */
  const step = useCallback(
    (delta: number) => {
      const next = FOCUS_TRACKS[(index + delta + FOCUS_TRACKS.length) % FOCUS_TRACKS.length];
      setTrackId(next.id);
      setPosition(0);
      if (playing) start(next.src);
      else setError(null);
    },
    [index, playing, start],
  );
  const nextTrack = useCallback(() => step(1), [step]);
  const prevTrack = useCallback(() => step(-1), [step]);

  const pickVibe = useCallback(
    (id: string) => {
      const chosen = FOCUS_TRACKS.find((entry) => entry.id === id);
      if (!chosen) return;
      setTrackId(chosen.id);
      if (playing) start(chosen.src);
    },
    [playing, start],
  );

  /**
   * The lyric line for the current second. `at` is a start time, so the line
   * shown is the last one that has started — that keeps it correct when the
   * student scrubs, loops, or switches songs mid-way.
   */
  const lyrics = FOCUS_LYRICS[track.id];
  const currentLine = useMemo(() => {
    if (!lyrics) return null;
    let line = lyrics.lines[0] ?? null;
    for (const entry of lyrics.lines) if (entry.at <= position + 0.35) line = entry;
    return line;
  }, [lyrics, position]);

  // The switch is off: the player is not on screen at all. Settings turns it on.
  if (!musicOn) return null;

  return (
    <div
      /* Bottom-LEFT: the Aarohi assistant owns the bottom-right corner.
         From md up the 15.5rem sidebar is there, so the player starts to the
         right of it instead of covering the last sidebar links. */
      className="no-print fixed z-40 left-3 bottom-24 md:bottom-6 md:left-[17rem] lg:left-[17.5rem]"
      aria-label="Focus Mode music player"
    >
      {open && (
        <section
          role="dialog"
          aria-label="Focus Mode"
          className="mb-3 w-[calc(100vw-1.5rem)] max-w-[19rem] sm:max-w-[21rem] neu-card p-3.5 sm:p-4"
        >
          <div className="flex items-start justify-between gap-2">
            <div className="flex items-center gap-2 min-w-0">
              <span className="grid h-8 w-8 place-items-center rounded-xl neu-pressed-sm text-(--color-accent-dark)">
                <Headphones size={15} />
              </span>
              <div className="min-w-0">
                <p className="font-display text-sm font-extrabold leading-tight">Focus Mode</p>
                <p className="text-[10px] text-(--color-muted)">Padhai ke liye soft music</p>
              </div>
            </div>
            <button
              type="button"
              onClick={() => setOpen(false)}
              aria-label="Close Focus Mode"
              className="neu-btn p-1.5 text-(--color-muted) hover:text-(--color-ink)"
            >
              <X size={14} />
            </button>
          </div>

          {/* Album tile: gradient drawn in CSS, spins only while playing. */}
          <div className="mt-3 flex items-center gap-3">
            <div
              className={`relative grid h-14 w-14 shrink-0 place-items-center rounded-2xl bg-gradient-to-br ${track.tint} shadow-(--neu-raised-sm)`}
            >
              <span
                className="text-xl"
                style={playing ? { animation: "focusSpin 9s linear infinite" } : undefined}
                aria-hidden
              >
                {track.emoji}
              </span>
              <span className="absolute inset-0 rounded-2xl bg-white/12" />
            </div>
            <div className="min-w-0 flex-1">
              <p className="truncate text-[13px] font-bold text-(--color-ink)">{track.title}</p>
              <p className="truncate text-[10px] text-(--color-muted)">{track.subtitle}</p>
              <div className="mt-1.5 flex h-4 items-end gap-[3px]" aria-hidden>
                {[0, 1, 2, 3, 4].map((bar) => (
                  <span
                    key={bar}
                    className={`w-[3px] rounded-full bg-(--color-accent) ${playing ? "eq-bar" : "opacity-30"}`}
                    style={{
                      height: `${[10, 15, 8, 13, 11][bar]}px`,
                      animationDelay: `${bar * 0.12}s`,
                    }}
                  />
                ))}
              </div>
            </div>
          </div>

          {/* Playlist: every bed, one tap each. Scrolls, so the panel stays small. */}
          <div className="mt-3 max-h-28 space-y-1 overflow-y-auto pr-0.5" role="group" aria-label="Choose a song">
            {FOCUS_TRACKS.map((entry, entryIndex) => (
              <button
                key={entry.id}
                type="button"
                onClick={() => pickVibe(entry.id)}
                aria-pressed={entry.id === track.id}
                aria-label={`${entry.title} — ${entry.vibe}`}
                className={`flex w-full items-center gap-2 rounded-xl px-2 py-1.5 text-left text-[10px] font-bold leading-tight transition ${
                  entry.id === track.id
                    ? "bg-(--color-accent) text-white shadow-(--neu-pressed-sm)"
                    : "neu-btn text-(--color-muted)"
                }`}
              >
                <span aria-hidden className="text-[13px]">{entry.emoji}</span>
                <span className="min-w-0 flex-1">
                  <span className="block truncate">{entry.title}</span>
                  <span className={`block truncate text-[9px] font-medium ${entry.id === track.id ? "text-white/75" : "opacity-70"}`}>
                    {entryIndex + 1}. {entry.subtitle}
                  </span>
                </span>
                {entry.id === track.id && playing && (
                  <span className="h-1.5 w-1.5 shrink-0 animate-pulse rounded-full bg-white" aria-hidden />
                )}
              </button>
            ))}
          </div>

          {/* Lyrics: the line for right now, with emoji, and a toggle. */}
          <div className="mt-2.5 rounded-xl bg-(--color-surface) px-2.5 py-2 shadow-(--neu-pressed-sm)">
            <div className="flex items-center justify-between gap-2">
              <span className="flex items-center gap-1 text-[9px] font-bold uppercase tracking-wider text-(--color-muted)">
                <Mic2 size={10} /> Lyrics
              </span>
              <button
                type="button"
                onClick={() => setLyricsOn(!lyricsOn)}
                aria-pressed={lyricsOn}
                aria-label={lyricsOn ? "Turn lyrics off" : "Turn lyrics on"}
                className={`rounded-full px-2 py-0.5 text-[9px] font-bold transition ${
                  lyricsOn ? "bg-(--color-accent) text-white" : "neu-btn text-(--color-muted)"
                }`}
              >
                {lyricsOn ? "ON" : "OFF"}
              </button>
            </div>
            {lyricsOn ? (
              <div aria-live="polite" className="mt-1.5 min-h-[2.2rem]">
                <p dir="auto" className="text-[11px] font-semibold leading-snug text-(--color-ink)">
                  {currentLine?.en ?? "🎵 Instrumental — bol nahi, sirf sur."}
                </p>
                {currentLine && (
                  <p dir="auto" className="text-[10px] leading-snug text-(--color-muted)">
                    {currentLine.hi}
                  </p>
                )}
              </div>
            ) : (
              <p className="mt-1 text-[10px] text-(--color-muted)">Lyrics band hain — toggle se chalu karo.</p>
            )}
          </div>

          {/* Transport */}
          <div className="mt-3 flex items-center justify-between gap-2">
            <button
              type="button"
              onClick={() => setMuted((value) => !value)}
              aria-label={muted ? "Unmute" : "Mute"}
              aria-pressed={muted}
              className="neu-btn p-2 text-(--color-muted) hover:text-(--color-ink)"
            >
              {muted ? <VolumeX size={15} /> : <Volume2 size={15} />}
            </button>
            <div className="flex flex-1 items-center gap-1.5">
              <button
                type="button"
                onClick={() => setVolume(Math.max(0, Number((volume - 0.1).toFixed(2))))}
                aria-label="Volume down"
                className="neu-btn p-1 text-(--color-muted)"
              >
                <Minus size={12} />
              </button>
              <label className="flex-1">
                <span className="sr-only">Volume</span>
                <input
                  type="range"
                  min={0}
                  max={100}
                  value={Math.round((muted ? 0 : volume) * 100)}
                  onChange={(event) => {
                    setMuted(false);
                    setVolume(Number(event.target.value) / 100);
                  }}
                  className="h-1.5 w-full cursor-pointer appearance-none rounded-full bg-(--color-surface) shadow-(--neu-pressed-sm) accent-(--color-accent)"
                />
              </label>
              <button
                type="button"
                onClick={() => setVolume(Math.min(1, Number((volume + 0.1).toFixed(2))))}
                aria-label="Volume up"
                className="neu-btn p-1 text-(--color-muted)"
              >
                <Plus size={12} />
              </button>
            </div>
            <button
              type="button"
              onClick={() => setLoop(!loop)}
              aria-label={loop ? "Loop off" : "Loop on"}
              aria-pressed={loop}
              className={`p-2 rounded-xl transition ${
                loop ? "neu-pressed-sm text-(--color-accent-dark)" : "neu-btn text-(--color-muted)"
              }`}
            >
              <Repeat size={15} />
            </button>
          </div>

          <p className="mt-2 flex items-center gap-1 text-[10px] text-(--color-muted)">
            <Music2 size={11} />
            {error ?? "Autoplay band hai — play dabane par hi music shuru hoga."}
          </p>
        </section>
      )}

      {/* The floating launcher: play/pause + switch vibe. */}
      <div className="flex items-center gap-1.5 sm:gap-2">
        <button
          type="button"
          onClick={() => setOpen((value) => !value)}
          aria-label={open ? "Hide music controls" : "Open Focus Mode music"}
          aria-expanded={open}
          className="neu-btn relative grid h-9 w-9 place-items-center text-(--color-accent-dark) sm:h-12 sm:w-12"
        >
          <Music2 size={16} />
          {playing && (
            <span className="absolute -right-0.5 -top-0.5 h-2.5 w-2.5 rounded-full bg-(--color-good) shadow-[0_0_0_2px_var(--color-surface)]" />
          )}
        </button>

        {/* Master OFF. Turns the music off *and* puts the player away until
            Settings (or this panel) turns it back on. */}
        <button
          type="button"
          onClick={() => {
            setMusicOn(false);
            setOpen(false);
          }}
          aria-label="Turn the music player off"
          title="Music OFF — Settings se dobara on kar sakte ho"
          className="neu-btn grid h-8 w-8 place-items-center text-(--color-muted) hover:text-(--color-danger) sm:h-10 sm:w-10"
        >
          <Power size={14} />
        </button>

        <button
          type="button"
          onClick={prevTrack}
          aria-label={`Previous song — ${FOCUS_TRACKS[(index - 1 + FOCUS_TRACKS.length) % FOCUS_TRACKS.length].title}`}
          title={`⏮ ${FOCUS_TRACKS[(index - 1 + FOCUS_TRACKS.length) % FOCUS_TRACKS.length].title}`}
          className="neu-btn grid h-9 w-9 place-items-center text-(--color-accent-dark) sm:h-10 sm:w-10"
        >
          <SkipBack size={14} />
        </button>

        <div className="relative">
          {playing && <span className="focus-halo rounded-full" aria-hidden />}
          <button
            type="button"
            onClick={toggle}
            aria-label={playing ? "Pause focus music" : "Play focus music"}
            aria-pressed={playing}
            className={`relative grid h-12 w-12 place-items-center rounded-full neu-btn-accent sm:h-16 sm:w-16 ${
              playing ? "focus-pulse" : ""
            }`}
          >
            {loading ? (
              <Loader2 size={24} className="animate-spin" />
            ) : playing ? (
              <Pause size={24} />
            ) : (
              <Play size={24} className="translate-x-0.5" />
            )}
          </button>
        </div>

        <button
          type="button"
          onClick={nextTrack}
          aria-label={`Next song — ${FOCUS_TRACKS[(index + 1) % FOCUS_TRACKS.length].title}`}
          title={`⏭ ${FOCUS_TRACKS[(index + 1) % FOCUS_TRACKS.length].title}`}
          className="neu-btn grid h-9 w-9 place-items-center text-(--color-accent-dark) sm:h-10 sm:w-10"
        >
          <SkipForward size={14} />
        </button>
      </div>

      {/* What is playing, under the button — readable without opening the panel. */}
      <p className="mt-1.5 text-center text-[10px] font-semibold text-(--color-muted)">
        {playing ? (
          <span className="inline-flex items-center gap-1">
            <span className="h-1.5 w-1.5 animate-pulse rounded-full bg-(--color-good)" />
            {track.vibe}
          </span>
        ) : (
          "Focus Mode"
        )}
      </p>
    </div>
  );
}
