/**
 * @license MIT
 * Focus Mode — a floating, neumorphic music player for long practice sessions.
 *
 * Deliberate decisions:
 *  - **No autoplay.** Nothing is loaded or played until the student presses
 *    play. Browsers block autoplay anyway, but the real reason is respect: a
 *    course page that starts singing is a bug, not a feature.
 *  - **One <audio> element**, created lazily on the first play, so the two beds
 *    are not downloaded on page load (they are ~380 kB each).
 *  - **Album art is drawn in CSS**, no image request, and the "playing" state
 *    pulses slowly (2.8s) instead of flashing.
 *  - Volume, chosen track and the play state survive navigation through
 *    localStorage, so switching chapters does not restart the music.
 *  - **One switch turns it off.** Settings ▸ Focus Mode music (or the power
 *    button in this panel) stops the sound *and* hides the player, which is
 *    what students asked for: "jab nahi chahiye to off kar do".
 *  - Lyrics are original Hinglish lines (src/data/focusLyrics.ts) timed to each
 *    bed, with emoji, shown only when the Lyric toggle is on.
 */
